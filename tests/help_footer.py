#!/usr/bin/env python3
"""Strict verifier for the one intentional `help -m` identity difference.

wash prints its own IMPLEMENTATION stanza instead of reproducing GNU bash's
copyright block.  This helper does **not** relax the byte comparison: it

  1. extracts bash's footer from the oracle output itself (from the last
     ``\\nSEE ALSO\\n`` to EOF), so no oracle copyright text is hardcoded;
  2. substitutes the independently maintained wash footer golden (below) into
     the oracle bytes and requires an exact byte match with wash's output;
  3. requires the substitution to be *reversible* -- replacing the wash footer
     back with bash's footer in wash's output must reproduce the oracle bytes
     exactly;
  4. requires both footers to occur the same number of times (77 times for
     ``help -m '*'``, once for a single topic);
  5. requires the version line inside that footer to be the string generated by
     ``tools/wash_version.sh`` (Cargo.toml + git tag/HEAD), passed in by the
     caller.  No version number is hardcoded here, so a version bump can never
     turn this check into a stale golden or a fake PASS.

Any other byte difference is a hard failure.  Usage::

    python3 tests/help_footer.py <oracle_stdout> <wash_stdout> <C|ZH> <version>
"""

import sys

# These are GOLDEN values maintained here, independently of src/help_pages.rs.
# If the implementation drifts, this test fails rather than adjusting itself.
# Only the version line is generated (see wash_footer below).
WASH_STANZA = {
    "C": (
        "    wash, version %s\n"
        "    A Rust reimplementation targeting GNU bash 5.3 semantics.\n"
        "    License: MIT OR Apache-2.0\n\n"
    ),
    "ZH": (
        "    wash，版本 %s\n"
        "    以 GNU bash 5.3 语义为目标的 Rust 重新实现。\n"
        "    许可证：MIT OR Apache-2.0\n\n"
    ),
}

HEAD = "\nSEE ALSO\n    bash(1)\n\nIMPLEMENTATION\n"
MARKER = b"\nSEE ALSO\n"


def wash_footer(locale, version):
    if not version or any(c in version for c in "\r\n"):
        raise ValueError("invalid generated version: %r" % version)
    return (HEAD + (WASH_STANZA[locale] % version)).encode("utf-8")


def first_diff(a, b):
    for i, (x, y) in enumerate(zip(a, b)):
        if x != y:
            return i
    return min(len(a), len(b))


def main():
    if len(sys.argv) != 5:
        print("usage: help_footer.py <oracle> <wash> <C|ZH> <version>")
        return 2
    locale = sys.argv[3]
    if locale not in WASH_STANZA:
        print("unknown locale: %s" % locale)
        return 2
    try:
        footer = wash_footer(locale, sys.argv[4])
    except ValueError as e:
        print("bad version: %s" % e)
        return 2
    with open(sys.argv[1], "rb") as f:
        oracle = f.read()
    with open(sys.argv[2], "rb") as f:
        wash = f.read()

    at = oracle.rfind(MARKER)
    if at < 0:
        print("oracle output has no SEE ALSO footer")
        return 1
    bash_footer = oracle[at:]
    if not bash_footer.endswith(b"\n\n"):
        print("unexpected oracle footer shape: %r" % bash_footer[-80:])
        return 1

    n_oracle = oracle.count(bash_footer)
    n_wash = wash.count(footer)
    if n_oracle < 1 or n_oracle != n_wash:
        print("footer count differs: oracle=%d wash=%d" % (n_oracle, n_wash))
        return 1

    expected = oracle.replace(bash_footer, footer)
    restored = wash.replace(footer, bash_footer)
    if expected != wash:
        i = first_diff(expected, wash)
        print("substituted oracle != wash at byte %d (expected %dB, got %dB)"
              % (i, len(expected), len(wash)))
        print("  expected: %r" % expected[max(0, i - 60):i + 60])
        print("  wash    : %r" % wash[max(0, i - 60):i + 60])
        return 1
    if restored != oracle:
        i = first_diff(restored, oracle)
        print("reverse substitution != oracle at byte %d" % i)
        return 1
    if b"GNU bash, version" in wash or b"GNU bash\xef\xbc\x8c" in wash:
        print("wash output still carries the bash IMPLEMENTATION identity")
        return 1
    print("OK: %d footer(s), byte-identical outside the wash identity block"
          % n_oracle)
    return 0


if __name__ == "__main__":
    sys.exit(main())
