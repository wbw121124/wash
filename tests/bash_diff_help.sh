#!/usr/bin/env bash
# Byte-for-byte comparison of `help` against GNU bash 5.3 (MSYS2 oracle).
#
# For every case we run BOTH shells with the same `-c` text and compare:
#   * stdout     -- strictly byte-for-byte (sha256 of the raw bytes)
#   * exit code  -- exactly equal
#   * stderr     -- byte-for-byte after normalizing ONLY the shell-name prefix
#                   (same rule as tests/bash_diff_builtins.sh):
#                     bash : "<path>/bash: line N: msg"      -> "msg"
#                     bash : "<path>/bash: 第 N 行：msg"      -> "msg"
#                     wash : "wash: msg"                     -> "msg"
#
# Two locales are covered: LC_ALL=C and LC_ALL=zh_CN.UTF-8 (bash's gettext
# translates page bodies, synopses, glob banners and diagnostics, but NOT the
# `help -d` short_doc -- see src/help_pages.rs).
#
# THE ONE INTENTIONAL EXCEPTION: `help -m` prints wash's own IMPLEMENTATION
# stanza instead of GNU bash's copyright block.  Those cases are NOT compared
# directly; tests/help_footer.py substitutes the wash footer golden into the
# oracle bytes, requires an exact match, requires the substitution to be
# reversible, and requires equal footer counts.  Any other differing byte is
# still a hard failure.
#
# Coverage:
#   * all 77 canonical help topics, individually, in C and zh_CN
#   * all 77 *list display values* used verbatim as NAME (`help '<display>'`)
#     in C and zh_CN, with rc + stdout + stderr byte-compared.  This pins the
#     "listed != queryable" boundary: the canonical-name loop above only proves
#     the keys work, it does NOT connect them to what the list actually prints.
#     The 77 values are extracted from the ORACLE list itself (column-major),
#     and a hard gate requires them to equal HELP_LIST_MAP's first column, so
#     this suite keeps no third copy of the strings under test.
#   * the bash-inherent `job_spec [&]` / `%` orphan in both locales, including
#     `help job_spec` rc=1 and `help '%'` rc=0 (NO alias may be added)
#   * all 77 topics in each of the four modes via `help '*'` / -s / -d / -m
#   * the no-argument list in BOTH locales: the version banner itself, the 5
#     banner sentences and the 77 synopsis lines are ALL byte-compared.  The
#     oracle's first line is extracted from the oracle bytes and substituted
#     with the version line generated by tools/wash_version.sh (Cargo.toml +
#     git tag/HEAD); tests/help_banner.py then requires complete equality with
#     wash's stdout, plus reversibility.  NOTHING is skipped with tail -n +2.
#   * glob patterns, multi-pattern title rules, aliases, options, errors
#   * wash-identity man footer (strict substitution, both locales)
#
# Run with:
#   MSYSTEM=MSYS "/d/msys2/usr/bin/bash.exe" -lc \
#       'cd <WASH_REPO> && bash tests/bash_diff_help.sh'
set -u

BASH_BIN="${BASH_BIN:-/d/msys2/usr/bin/bash.exe}"
REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
if [ -z "${WASH_BIN:-}" ]; then
    if [ -x "$REPO_ROOT/target/debug/wash.exe" ]; then
        WASH_BIN="$REPO_ROOT/target/debug/wash.exe"
    else
        WASH_BIN="$REPO_ROOT/target/debug/wash"
    fi
fi
[ -x "$BASH_BIN" ] || { echo "FATAL: oracle not found: $BASH_BIN"; exit 1; }
[ -x "$WASH_BIN" ] || { echo "FATAL: wash not found: $WASH_BIN"; exit 1; }
command -v python3 >/dev/null 2>&1 || { echo "FATAL: python3 required for help_footer.py"; exit 1; }
[ -f "$REPO_ROOT/tests/help_footer.py" ] || { echo "FATAL: tests/help_footer.py missing"; exit 1; }

export LC_ALL=C
export LANG=C
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT
export HOME="$TMP/home"
mkdir -p "$HOME"

# Version gate: the banner IS compared, so its expected text must be generated
# from Cargo.toml + git tag/HEAD.  A stale binary (old version) aborts here
# instead of producing diffs that could be explained away.
[ -f "$REPO_ROOT/tools/wash_version.sh" ] || {
    echo "FATAL: tools/wash_version.sh missing"; exit 1; }
WASH_FULL_VER="$(bash "$REPO_ROOT/tools/wash_version.sh")" || {
    echo "FATAL: version generator failed (git metadata missing?)"; exit 1; }
[ -n "$WASH_FULL_VER" ] || { echo "FATAL: empty generated version"; exit 1; }
"$WASH_BIN" --version > "$TMP/ver.out" 2>&1
ver_got="$(cat "$TMP/ver.out")"
[ "$ver_got" = "wash $WASH_FULL_VER" ] || {
    echo "FATAL: stale wash binary: expected [wash $WASH_FULL_VER] got [$ver_got]"; exit 1; }
echo "hard gate: generated version [$WASH_FULL_VER] matches binary"

PASS=0
FAIL=0

# Hard gate: if the zh_CN locale silently falls back to C on either side,
# both shells would emit English and every Chinese case would pass vacuously.
# Require the oracle's Chinese page to actually contain non-ASCII bytes.
LC_ALL=zh_CN.UTF-8 LANG=zh_CN.UTF-8 "$BASH_BIN" -c 'help cd' > "$TMP/zh_gate.out"
python3 -c 'import sys; d=open(sys.argv[1],"rb").read(); sys.exit(0 if any(b>127 for b in d) else 1)' \
    "$TMP/zh_gate.out" || {
    echo "FATAL: oracle zh_CN.UTF-8 locale is not active (help cd is pure ASCII)"
    exit 1
}
echo "hard gate: oracle zh_CN locale active ($(wc -c < "$TMP/zh_gate.out")B, non-ASCII present)"

# Hard gate #2: the oracle's Chinese no-argument LIST body (line 9 onward)
# must itself contain non-ASCII bytes.  Without it, a locale fallback could
# make both shells emit the English list and the list cases would pass vacuously.
LC_ALL=zh_CN.UTF-8 LANG=zh_CN.UTF-8 "$BASH_BIN" -c 'help' > "$TMP/zh_list_gate.out"
python3 -c 'import sys; rows=open(sys.argv[1],"rb").read().splitlines()[8:]; sys.exit(0 if any(any(b>127 for b in r) for r in rows) else 1)' \
    "$TMP/zh_list_gate.out" || {
    echo "FATAL: oracle zh_CN help list body is not localized (pure ASCII)"
    exit 1
}
echo "hard gate: oracle zh_CN help list body localized ($(wc -c < "$TMP/zh_list_gate.out")B)"

sha() { sha256sum "$1" | cut -d' ' -f1; }
normalize_stderr() {
    sed -E 's#^[^:]*bash(\.exe)?: (line [0-9]+: |第 [0-9]+ 行：)?##; s#^wash(\.exe)?: ##' "$1"
}
first_diffs() {
    awk 'NR==FNR{a[FNR]=$0;n=FNR;next}{b[FNR]=$0;m=FNR}END{
        lim=(n<m?n:m); c=0;
        for(i=1;i<=lim;i++) if(a[i]!=b[i]){printf "    line %d\n      bash: [%s]\n      wash: [%s]\n",i,a[i],b[i]; if(++c>=5) exit}
        if(n!=m) printf "    line count differs: bash=%d wash=%d\n",n,m
    }' "$1" "$2"
}

# pair LABEL TEXT [LOCALE] [MODE]
#   LOCALE: C (default) | ZH
#   MODE  : plain (default, byte compare) | man (strict footer substitution)
#           | list (strict generated-banner substitution, NO line is skipped)
pair() {
    local label="$1" text="$2" loc="${3:-C}" mode="${4:-plain}"
    local rb rw ho_b ho_w he_b he_w stdout_ok=0 stdout_note=""
    if [ "$loc" = ZH ]; then
        LC_ALL=zh_CN.UTF-8 LANG=zh_CN.UTF-8 "$BASH_BIN" -c "$text" > "$TMP/b.out" 2> "$TMP/b.err"; rb=$?
        LC_ALL=zh_CN.UTF-8 LANG=zh_CN.UTF-8 "$WASH_BIN" -c "$text" > "$TMP/w.out" 2> "$TMP/w.err"; rw=$?
    else
        "$BASH_BIN" -c "$text" > "$TMP/b.out" 2> "$TMP/b.err"; rb=$?
        "$WASH_BIN" -c "$text" > "$TMP/w.out" 2> "$TMP/w.err"; rw=$?
    fi
    normalize_stderr "$TMP/b.err" > "$TMP/b.err.n"
    normalize_stderr "$TMP/w.err" > "$TMP/w.err.n"
    ho_b="$(sha "$TMP/b.out")"; ho_w="$(sha "$TMP/w.out")"
    he_b="$(sha "$TMP/b.err.n")"; he_w="$(sha "$TMP/b.err.n")"

    local frc=0
    if [ "$mode" = man ]; then
        stdout_note="$(python3 "$REPO_ROOT/tests/help_footer.py" \
            "$TMP/b.out" "$TMP/w.out" "$loc" "$WASH_FULL_VER" 2>&1)"
        frc=$?
        [ "$frc" -eq 0 ] && stdout_ok=1
    elif [ "$mode" = list ]; then
        stdout_note="$(python3 "$REPO_ROOT/tests/help_banner.py" \
            "$TMP/b.out" "$TMP/w.out" "$WASH_FULL_VER" 2>&1)"
        frc=$?
        [ "$frc" -eq 0 ] && stdout_ok=1
    else
        [ "$ho_b" = "$ho_w" ] && stdout_ok=1
    fi

    if [ "$rb" = "$rw" ] && [ "$stdout_ok" -eq 1 ] && [ "$he_b" = "$he_w" ]; then
        PASS=$((PASS+1))
    else
        FAIL=$((FAIL+1))
        echo "FAIL [$label] loc=$loc mode=$mode: $text"
        echo "    rc: bash=$rb wash=$rw   stdout: bash=$(wc -c < "$TMP/b.out")B wash=$(wc -c < "$TMP/w.out")B"
        echo "    stderr: bash=$(wc -c < "$TMP/b.err.n")B wash=$(wc -c < "$TMP/w.err.n")B"
        if [ "$stdout_ok" -ne 1 ]; then
            echo "    stdout check ($mode): $stdout_note"
            if [ "$mode" = plain ]; then
                echo "    stdout differs:"; first_diffs "$TMP/b.out" "$TMP/w.out"
            fi
        fi
        if [ "$he_b" != "$he_w" ]; then
            echo "    stderr differs:"
            first_diffs "$TMP/b.err.n" "$TMP/w.err.n"
        fi
    fi
}

# The 77 canonical topic names, in bash 5.3's own order (from `help -s '*'`).
# They stay English in both locales -- only the page text is translated.
TOPICS=(
    '!' '%' '(( ... ))' '.' ':' '[' '[[ ... ]]' alias bg bind break builtin
    caller case cd command compgen complete compopt continue coproc declare
    dirs disown echo enable eval exec exit export false fc fg for 'for (('
    function getopts hash help history if jobs kill let local logout mapfile
    popd printf pushd pwd read readarray readonly return select set shift
    shopt source suspend test time times trap true type typeset ulimit umask
    unalias unset until variables wait while '{ ... }'
)
[ "${#TOPICS[@]}" -eq 77 ] || { echo "FATAL: expected 77 topics, got ${#TOPICS[@]}"; exit 1; }

# The 77 displayed synopses of the no-argument list, taken from the ORACLE's
# own C-locale list (39 column-major rows -> 39 left + 38 right), identical to
# the split rule in tools/gen_help_pages.py.  A hard gate inside the probe
# requires them to equal HELP_LIST_MAP's first column, so this suite cannot
# silently test a stale third copy of the strings.
LC_ALL=C LANG=C "$BASH_BIN" -c 'help' > "$TMP/oracle_list.out"
python3 - "$TMP/oracle_list.out" "$REPO_ROOT/src/help_pages.rs" > "$TMP/list_display.txt" <<'PY'
import re
import sys

lines = open(sys.argv[1], "rb").read().decode("utf-8").splitlines()
body = lines[8:]
assert len(body) == 39, ("expected 39 list rows", len(body))
left, right = [], []
for row in body:
    assert row.startswith(" "), row
    m = re.search(r" {2,}", row[1:])
    if m:
        left.append(row[1:1 + m.start()])
        r = row[1 + m.end():].rstrip()
        if r:
            right.append(r)
    else:
        left.append(row[1:])
entries = left + right
assert len(left) == 39 and len(right) == 38 and len(entries) == 77, \
    (len(left), len(right), len(entries))

rust = open(sys.argv[2], encoding="utf-8").read()
marker = "pub(crate) const HELP_LIST_MAP: &[(&str, &str)] = &["
assert marker in rust, "HELP_LIST_MAP missing from src/help_pages.rs"
block = rust.split(marker, 1)[1].split("\n];", 1)[0]
col1 = re.findall(r'\(\s*r#"(.*?)"#,', block)
assert len(col1) == 77, ("HELP_LIST_MAP first column size", len(col1))
assert col1 == entries, "HELP_LIST_MAP display column != oracle C list"
for e in entries:
    # A single-quoted literal must be able to carry the whole value unchanged.
    assert "'" not in e and "\n" not in e, ("unsafe display value", e)
    print(e)
PY
[ "$?" -eq 0 ] || { echo "FATAL: cannot derive the 77 list display values"; exit 1; }
mapfile -t LIST_DISPLAY < "$TMP/list_display.txt"
[ "${#LIST_DISPLAY[@]}" -eq 77 ] || {
    echo "FATAL: expected 77 display values, got ${#LIST_DISPLAY[@]}"; exit 1; }
echo "hard gate: 77 list display values == HELP_LIST_MAP first column"

echo "=== [C] 每个主题的完整手册页（77 例）==="
for t in "${TOPICS[@]}"; do
    pair "topic:$t" "help '$t'"
done

# 77 条清单显示值原样当 NAME：bash 5.3 的清单是短摘要而非查找键，实测
# 72/77 查不到。两侧 rc + stdout + stderr 全量对拍（plain 模式，不切任何行），
# 差异由 first_diffs 定位。显示值含空格 / `>` / `[` / `;` / `&` / `!` / `{`，
# 但不含单引号，故整词单引号即可保证一字不差地传成一个 argv。
echo "=== [C] 清单显示值原样作为 NAME（77 例，rc+stdout+stderr 逐字节对拍）==="
for i in "${!LIST_DISPLAY[@]}"; do
    d="${LIST_DISPLAY[$i]}"
    pair "list-name:$((i + 1)):$d" "help '$d'"
done

echo "=== [C] 四种模式的全量拼接（每例覆盖全部 77 页）==="
pair 'all:full'      "help '*'"
pair 'all:short'     "help -s '*'"
pair 'all:desc'      "help -d '*'"
pair 'all:man'       "help -m '*'" C man
pair 'all:empty'     "help ''"
pair 'all:s-empty'   "help -s -- ''"

echo "=== [C] 单主题的选项形式 ==="
for t in cd '%' '(( ... ))' '[[ ... ]]' variables true; do
    pair "s:$t"  "help -s -- '$t'"
    pair "d:$t"  "help -d -- '$t'"
    pair "m:$t"  "help -m -- '$t'" C man
done

echo "=== [C] 无参数清单（版本行也逐字节对拍，不跳过）==="
pair 'list:plain'  'help'       C list
pair 'list:-s'     'help -s'    C list
pair 'list:-d'     'help -d'    C list
pair 'list:--'     'help --'    C list
pair 'list:-m'     'help -m'    C list

echo "=== [C] glob / 多 pattern / 别名 / 选项 / 错误 ==="
pair 'glob:c*'        "help 'c*'"
pair 'glob:cd*'       "help 'cd*'"
pair 'glob:for*'      "help 'for*'"
pair 'glob:*a*'       "help '*a*'"
pair 'glob:class'     "help '[cf]*'"
pair 'glob:q'         "help 'c?'"
pair 'glob:none'      "help 'zz*'"
pair 'glob:two'       "help 'c*' 'z*'"
pair 'glob:then-bad'  "help 'c*' zzz"
pair 'bad:then-glob'  "help zzz 'c*'"
pair 'glob:bad-rc'    "help 'zz*'; echo \"rc=\$?\""
pair 'alias:[[[['     "help '[['"
pair 'alias:(('       "help '(('"
pair 'alias:{'        "help '{'"
pair 'exact:[[...]]'  "help '[[ ... ]]'"
pair 'exact:{...}'    "help '{ ... }'"
pair 'multi:two'      "help cd pwd"
pair 'multi:hit+miss' "help cd nosuch"
pair 'multi:miss+hit' "help nosuch cd"
pair 'multi:two-bad'  "help aaa bbb; echo \"rc=\$?\""
pair 'multi:three-bad' "help aaa bbb ccc; echo \"rc=\$?\""
pair 'multi:exact+glob' "help cd 'c*'"
pair 'opt:-dms'       "help -dms cd"
pair 'opt:-sd'        "help -sd cd"
pair 'opt:-ms'        "help -ms cd" C man
pair 'opt:-x'         "help -x cd; echo \"rc=\$?\""
pair 'opt:after-name' "help cd -s"
pair 'opt:-'          "help -; echo \"rc=\$?\""
pair 'opt:--name'     "help -- cd"
pair 'err:nosuch'     "help nosuchbuiltin; echo \"rc=\$?\""
# bash 5.3 固有的「列出≠可查」孤例，**不是 wash 缺陷**：无参清单第 2 项显示
# `job_spec [&]`，但该页的规范名是 `%`；oracle 自身 `help job_spec` 就是 rc=1。
# wash 必须保持 rc=1，禁止为 job_spec 补别名（会破坏逐字节兼容）。以下几条
# 把 rc + stdout + stderr 全量对拍，不裁剪版本行或任何其它输出。
pair 'err:job_spec'    "help job_spec; echo \"rc=\$?\""
pair 'orphan:job_spec' "help job_spec; echo \"rc=\$?\""
pair 'orphan:pct'      "help '%'; echo \"rc=\$?\""
pair 'orphan:pct-page' "help '%'"
pair 'err:upper'      "help CD; echo \"rc=\$?\""
pair 'err:brace'      "help '}'; echo \"rc=\$?\""
pair 'err:s-none'     "help -s nosuch; echo \"rc=\$?\""

echo "=== [zh_CN] 每个主题的完整手册页（77 例）==="
for t in "${TOPICS[@]}"; do
    pair "zh:topic:$t" "help '$t'" ZH
done

# 同一组 77 条 C 清单显示值在 zh_CN 下原样当 NAME：诊断译文也被逐字节对拍。
echo "=== [zh_CN] 清单显示值原样作为 NAME（77 例，rc+stdout+stderr 逐字节对拍）==="
for i in "${!LIST_DISPLAY[@]}"; do
    d="${LIST_DISPLAY[$i]}"
    pair "zh:list-name:$((i + 1)):$d" "help '$d'" ZH
done

echo "=== [zh_CN] 四种模式的全量拼接 ==="
pair 'zh:all:full'    "help '*'" ZH
pair 'zh:all:short'   "help -s '*'" ZH
pair 'zh:all:desc'    "help -d '*'" ZH
pair 'zh:all:man'     "help -m '*'" ZH man
pair 'zh:all:empty'   "help ''" ZH
pair 'zh:all:s-empty' "help -s -- ''" ZH

echo "=== [zh_CN] 单主题的选项形式 ==="
for t in cd '%' '(( ... ))' '[[ ... ]]' variables true; do
    pair "zh:s:$t"  "help -s -- '$t'" ZH
    pair "zh:d:$t"  "help -d -- '$t'" ZH
    pair "zh:m:$t"  "help -m -- '$t'" ZH man
done

echo "=== [zh_CN] 无参数清单：版本行 + 抬头 5 句 + 77 条中文摘要（不跳过）==="
pair 'zh:list:plain'  'help'       ZH list
pair 'zh:list:-s'     'help -s'    ZH list
pair 'zh:list:-d'     'help -d'    ZH list
pair 'zh:list:--'     'help --'    ZH list
pair 'zh:list:-m'     'help -m'    ZH list

echo "=== [zh_CN] glob / 多 pattern / 别名 / 选项 / 错误 ==="
pair 'zh:glob:c*'        "help 'c*'" ZH
pair 'zh:glob:cd*'       "help 'cd*'" ZH
pair 'zh:glob:for*'      "help 'for*'" ZH
pair 'zh:glob:*a*'       "help '*a*'" ZH
pair 'zh:glob:class'     "help '[cf]*'" ZH
pair 'zh:glob:q'         "help 'c?'" ZH
pair 'zh:glob:none'      "help 'zz*'" ZH
pair 'zh:glob:two'       "help 'c*' 'z*'" ZH
pair 'zh:glob:then-bad'  "help 'c*' zzz" ZH
pair 'zh:bad:then-glob'  "help zzz 'c*'" ZH
pair 'zh:alias:[[[['     "help '[['" ZH
pair 'zh:alias:(('       "help '(('" ZH
pair 'zh:alias:{'        "help '{'" ZH
pair 'zh:multi:two'      "help cd pwd" ZH
pair 'zh:multi:hit+miss' "help cd nosuch" ZH
pair 'zh:multi:miss+hit' "help nosuch cd" ZH
pair 'zh:multi:two-bad'  "help aaa bbb; echo \"rc=\$?\"" ZH
pair 'zh:multi:three-bad' "help aaa bbb ccc; echo \"rc=\$?\"" ZH
pair 'zh:multi:exact+glob' "help cd 'c*'" ZH
pair 'zh:opt:-dms'       "help -dms cd" ZH
pair 'zh:opt:-sd'        "help -sd cd" ZH
pair 'zh:opt:-ms'        "help -ms cd" ZH man
pair 'zh:opt:-x'         "help -x cd; echo \"rc=\$?\"" ZH
pair 'zh:opt:-'          "help -; echo \"rc=\$?\"" ZH
pair 'zh:opt:--name'     "help -- cd" ZH
pair 'zh:err:nosuch'     "help nosuchbuiltin; echo \"rc=\$?\"" ZH
# 孤例在 zh_CN 同样成立（诊断译文也逐字节对拍），见 C 段注释。
pair 'zh:err:job_spec'     "help job_spec; echo \"rc=\$?\"" ZH
pair 'zh:orphan:job_spec'  "help job_spec; echo \"rc=\$?\"" ZH
pair 'zh:orphan:pct'       "help '%'; echo \"rc=\$?\"" ZH
